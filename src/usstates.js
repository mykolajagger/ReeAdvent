const MARGIN = 0.07;   // ≈ 7 км: трохи більше за радіус пошуку закладів
/** Штати, рамка яких містить місто; якщо жодного (острови, помилка рамки) — найближчий за відстанню до центру рамки. */
export function statesFor(lat, lon, boxes = US_BOX) {
  const hit = Object.entries(boxes).filter(([, b]) => lat >= b[0] - MARGIN && lat <= b[2] + MARGIN && lon >= b[1] - MARGIN && lon <= b[3] + MARGIN).map(([k]) => k);
  if (hit.length) return hit;
  let best = null, bd = Infinity;
  for (const [k, b] of Object.entries(boxes)) { const d = (lat - (b[0] + b[2]) / 2) ** 2 + (lon - (b[1] + b[3]) / 2) ** 2; if (d < bd) { bd = d; best = k; } }
  return best ? [best] : [];
}
/** Дочірні вигрузки (штати) батьківської з каталогу Geofabrik: { 'AL': { id, url } } за кодом iso3166-2 «US-AL». */
export function childExtracts(index, parentId, cc) {
  const out = {};
  for (const f of (index && index.features) || []) {
    const p = f && f.properties; if (!p || p.parent !== parentId || !p.urls || !p.urls.pbf) continue;
    for (const c of [].concat(p['iso3166-2'] || [])) if (typeof c === 'string' && c.toUpperCase().startsWith(cc + '-')) out[c.toUpperCase().slice(cc.length + 1)] = { id: p.id, url: p.urls.pbf };
  }
  return out;
}
/** План: для кожного штату — міста, яким потрібна його вигрузка; для кожного міста — множина штатів, які ще чекаємо. Штати з найбільшою кількістю міст першими. */
export function planStates(cities, extracts) {
  const byState = new Map(), waiting = new Map();
  for (const c of cities) {
    const st = statesFor(c.lat, c.lon).filter(s => extracts[s]); if (!st.length) continue;
    waiting.set(c.id, new Set(st)); for (const s of st) (byState.get(s) || byState.set(s, []).get(s)).push(c);
  }
  const order = [...byState.keys()].sort((a, b) => byState.get(b).length - byState.get(a).length);
  return { byState, waiting, order };
}
